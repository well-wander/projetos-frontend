// recebe dois números e retorna a multiplicação deles
function multiplicar(a: number, b: number): number {
    return a * b;
}

// recebe um nome e retorna "Olá " + nome
function saudar(nome: string): string {
    return "Olá " + nome;
}

console.log(multiplicar(6, 7)); // 42
console.log(saudar("General Kenobi")); // Olá General Kenobi
